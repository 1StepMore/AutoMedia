"""Credentials matrix must never drift from adapter code (#456).

``docs/dev/adapter-credentials-matrix.md`` is generated by
``scripts/generate_adapter_credentials_matrix.py`` from the adapter modules
themselves.  This test regenerates the content in-process and fails when the
committed file no longer matches what the code reads — so a new credential
env, a new platform, or an is_stub flip cannot land without updating the
matrix.
"""

from __future__ import annotations

from scripts.generate_adapter_credentials_matrix import DOC_PATH, build_markdown


def test_credentials_matrix_matches_code() -> None:
    committed = DOC_PATH.read_text(encoding="utf-8")
    assert committed == build_markdown(), (
        "docs/dev/adapter-credentials-matrix.md drifted from adapter code — "
        "re-run: python scripts/generate_adapter_credentials_matrix.py"
    )


def test_matrix_covers_every_adapter() -> None:
    from tests.test_adapters.test_platform_contracts import ADAPTER_CLASSES

    doc = DOC_PATH.read_text(encoding="utf-8")
    for adapter_cls in ADAPTER_CLASSES:
        name = adapter_cls().platform_name
        assert f"| {name} |" in doc, f"{name} missing from the credentials matrix"
