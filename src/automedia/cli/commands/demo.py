"""``automedia demo`` — credential-free sample production (#360).

Runs the real pipeline in a hermetic sandbox: the deterministic fake-LLM
(``AUTOMEDIA_FAKE_LLM=1``), the local Pillow image engine, and a brand-new
``AUTOMEDIA_CONFIG_DIR`` + project dir under the user's demo folder. No
credentials, no network — the output is a complete, gate-checked sample
project for presentations and smoke tests.

Everything produced is **synthetic demo data** (red line 4): it demonstrates
the pipeline; it is not production content.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

import typer

logger = logging.getLogger(__name__)

app = typer.Typer(help="Produce a complete sample project with zero credentials.")

_DEMO_MARKER = "DEMO.md"

_DEMO_README = """# AutoMedia Demo Project（演示数据）

This project was generated by `automedia demo` with:

- the deterministic fake LLM (`AUTOMEDIA_FAKE_LLM=1`) — no model provider contacted
- the local Pillow image engine (`engines.image.chain: [local]`) — no ComfyUI
- a fresh `AUTOMEDIA_CONFIG_DIR` — none of your real configuration was touched

**This is synthetic demo data for presentations and smoke tests** — it is not
production content. Delete the whole directory whenever you like.
"""


def _demo_dirs() -> tuple[Path, Path]:
    """Return (config_dir, projects_dir) inside the user's demo folder."""
    base = Path.home() / ".automedia" / "demo"
    return base / "config", base / "projects"


@app.command()
def demo(
    mode: str = typer.Option("text_with_cover", "--mode", help="Pipeline mode for the demo run."),
    keep_env: bool = typer.Option(
        False, "--keep-env", help="Leave the demo env vars set (for follow-up commands)."
    ),
) -> None:
    """Produce a complete sample project — no credentials, no network.

    Everything is synthetic (fake-LLM text + Pillow-rendered images). The run
    uses an isolated config dir, so your real configuration is untouched.
    """
    config_dir, projects_dir = _demo_dirs()
    config_dir.mkdir(parents=True, exist_ok=True)
    projects_dir.mkdir(parents=True, exist_ok=True)

    # Hermetic env: fake LLM + local-only image chain + isolated dirs.
    os.environ["AUTOMEDIA_FAKE_LLM"] = "1"
    os.environ["AUTOMEDIA_CONFIG_DIR"] = str(config_dir)
    os.environ["AUTOMEDIA_PROJECTS_DIR"] = str(projects_dir)
    os.environ.pop("AUTOMEDIA_LLM_API_KEY", None)

    from automedia import run_full_pipeline
    from automedia.core.env_overlay import reset_dotenv_overlay_cache

    reset_dotenv_overlay_cache()

    typer.echo("Demo sandbox:")
    typer.echo(f"  config dir : {config_dir}")
    typer.echo(f"  projects   : {projects_dir}")
    typer.echo("  LLM        : AUTOMEDIA_FAKE_LLM=1 (deterministic, offline)")
    typer.echo("  images     : local Pillow engine")
    typer.echo("")

    try:
        result = run_full_pipeline(
            topic="AutoMedia 功能演示：从主题到成品的自动化流水线",
            brand="demo-brand",
            mode=mode,
        )
    except Exception as exc:
        typer.secho(f"Demo run failed: {exc}", fg=typer.colors.RED)
        raise typer.Exit(1) from exc

    project_id = getattr(result, "project_id", "") or ""
    status = getattr(result, "status", "")
    project_dir = ""
    try:
        from automedia.core.project import find_project_dir

        project_dir = find_project_dir(project_id, str(projects_dir)) or ""
    except Exception:
        project_dir = ""

    marker = Path(project_dir) / _DEMO_MARKER if project_dir else Path(projects_dir) / _DEMO_MARKER
    marker.write_text(_DEMO_README, encoding="utf-8")

    typer.echo("")
    typer.secho("Demo complete.", fg=typer.colors.GREEN)
    typer.echo(f"  project : {project_id} (status: {status})")
    typer.echo(f"  output  : {project_dir or projects_dir}")
    typer.echo(f"  marker  : {marker}")
    if not keep_env:
        # restore isolation for the current process's follow-up commands
        for key in ("AUTOMEDIA_FAKE_LLM", "AUTOMEDIA_CONFIG_DIR", "AUTOMEDIA_PROJECTS_DIR"):
            os.environ.pop(key, None)
        reset_dotenv_overlay_cache()
        typer.echo("  (demo env vars unset — use --keep-env to keep them)")
    else:
        typer.echo("  (demo env vars left set — follow-up commands share the sandbox)")
