"""Generate the platform adapter credentials matrix from adapter code (#456).

Derives, per platform module under ``adapters/platforms/``:

- ``platform_name`` (from the adapter class)
- automation honesty: ``is_stub`` flag (manual-only platforms)
- credential requirements: every ``load_credential_or_env(...)`` /
  ``load_credential(...)`` / ``env_lookup(...)`` reference in the module
  source, so the matrix can never drift from what the code actually reads
- what can be verified tonight: 干跑 (always), 真发 (needs credentials),
  不可自动 (stub platforms)

Writes ``docs/dev/adapter-credentials-matrix.md`` with an AUTO-GENERATED
banner.  ``tests/test_adapters/test_credentials_matrix.py`` regenerates the
content and fails when the committed file drifts from the code.
"""

from __future__ import annotations

import importlib
import inspect
import pkgutil
import re
from pathlib import Path

import automedia.adapters.platforms as platforms_pkg
from automedia.adapters.base import BasePlatformAdapter

DOC_PATH = Path("docs/dev/adapter-credentials-matrix.md")

_CRED_RES = (
    re.compile(r'load_credential_or_env\("([A-Z_]+)"(?:,\s*"([a-z0-9_]+)")?'),
    re.compile(r'load_credential\("([a-z0-9_]+)"'),
    re.compile(r'env_lookup\("([A-Z_]+)"'),
)

_BANNER = (
    "<!-- AUTO-GENERATED by scripts/generate_adapter_credentials_matrix.py — "
    "do not hand-edit.  tests/test_adapters/test_credentials_matrix.py fails "
    "when this file drifts from adapter code. -->"
)


def _discover() -> list[tuple[type[BasePlatformAdapter], str]]:
    found: list[tuple[type[BasePlatformAdapter], str]] = []
    for info in pkgutil.iter_modules(platforms_pkg.__path__):
        mod = importlib.import_module(f"automedia.adapters.platforms.{info.name}")
        source = inspect.getsource(mod)
        for _, obj in inspect.getmembers(mod, inspect.isclass):
            if (
                issubclass(obj, BasePlatformAdapter)
                and obj is not BasePlatformAdapter
                and obj.__module__ == mod.__name__
            ):
                found.append((obj, source))
    return sorted(found, key=lambda pair: pair[0]().platform_name)


def _credentials(source: str) -> list[str]:
    envs: list[str] = []
    for pattern in _CRED_RES:
        for match in pattern.findall(source):
            name = match[0] if isinstance(match, tuple) else match
            if name and name not in envs:
                envs.append(name)
    return envs


def build_markdown() -> str:
    lines = [
        _BANNER,
        "",
        "# 平台适配器凭证矩阵（从代码推导生成，#456）",
        "",
        "每行一个平台：需要的凭证（env 名 / 加密存储键）、认证方式归属、",
        "当前是否具备、以及**零凭证条件下能验到什么程度**。",
        "",
        "- **干跑**：`PublishEngine.publish_all(..., dry_run=True)` —— 零凭证可跑，"
        "不发任何网络请求。",
        "- **真发**：需要该行凭证全部就位后才可能；本矩阵生成时一律未具备。",
        "- **不可自动**：`is_stub=True` 平台没有公开自动化 API，代码层明确拒绝自动发布。",
        "",
        "| 平台 | is_stub | 凭证（env / 存储键） | 认证方式 | 当前具备 | 可验程度 |",
        "|:--|:--|:--|:--|:--|:--|",
    ]
    for cls, source in _discover():
        adapter = cls()
        creds = _credentials(source)
        cred_cell = "<none>" if not creds else " / ".join(creds)
        if getattr(cls, "is_stub", False):
            auth = "manual（平台无公开 API，代码显式拒绝自动发布）"
            verify = "干跑 ✅ · 真发 ❌ 不可自动"
        elif "COOKIE" in cred_cell or "cookie" in cred_cell:
            auth = "cookie 会话（env 或加密存储）"
            verify = "干跑 ✅ · 真发 ❌（缺凭证）"
        elif "TOKEN" in cred_cell or "token" in cred_cell:
            auth = "token/oauth（env 或加密存储）"
            verify = "干跑 ✅ · 真发 ❌（缺凭证）"
        else:
            auth = "api_key/oauth 凭证（env 或加密存储）"
            verify = "干跑 ✅ · 真发 ❌（缺凭证）"
        lines.append(
            f"| {adapter.platform_name} | {getattr(cls, 'is_stub', False)} "
            f"| {cred_cell} | {auth} | ❌ 未配置 | {verify} |"
        )
    lines += [
        "",
        "## 与 README「Adapter Status」的关系",
        "",
        "README 的 real-automation 判定以 `is_stub=False` 为准（12 个平台）；"
        "其中零凭证条件下没有任何一个真正发布过（见本表「当前具备」列）。"
        "README 文案层面的修正单独走 issue，不在本矩阵范围内（#456 边界）。",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(build_markdown(), encoding="utf-8")
    print(f"wrote {DOC_PATH}")


if __name__ == "__main__":
    main()
