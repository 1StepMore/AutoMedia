#!/usr/bin/env python3
"""Regression check for issue #208: model-config write guards.

Proves the four guards that the clobbered ``~/.automedia/model_config.yaml``
made necessary, against the real library and CLI surface:

1. an explicitly empty ``llm.text_generation.provider`` (or ``base_url``) is
   refused — the merge write never lands, so no config can be rewritten into
   a blank provider;
2. an existing ``model_config.yaml`` is copied to
   ``model_config.yaml.bak-<UTC timestamp>`` before it is overwritten;
3. a write targeting the real user config directory is refused unless the
   caller opts in with ``allow_user_scope=True``;
4. ``automedia doctor`` reports an empty ``provider`` as an error instead of
   letting the environment fallback mask it.

Safe to run standalone: every write happens inside a TemporaryDirectory, the
process points at a throwaway ``HOME``, and the real user config directory is
snapshotted first and verified untouched afterwards.  Exits 0 and prints
``REG208_GUARDS_ENFORCED`` on success, else exits non-zero naming the guard
that did not hold.
"""

from __future__ import annotations

import json
import os
import site
import subprocess
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
_SRC = _REPO_ROOT / "src"
if _SRC.is_dir() and str(_SRC) not in sys.path:
    # Run against the working tree, never a site-packages copy.
    sys.path.insert(0, str(_SRC))

_CONFIG_DIR_ENV = "AUTOMEDIA_CONFIG_DIR"

_SEEDED_CONFIG = (
    "# AutoMedia LLM configuration\n"
    "# Generated by `automedia init` — chain note: AMD primary.\n"
    "llm:\n"
    "  text_generation:\n"
    "    provider: amd\n"
    "    model: DeepSeek-V4-Flash\n"
    "    api_key: sk-seeded\n"
    "    base_url: https://developer.amd.com.cn/radeon/api/v1\n"
    "    fallback:\n"
    "      - provider: fallback-provider\n"
    "        model: fallback-model\n"
)


def _snapshot_dir(path: Path) -> list[tuple[str, int, int]]:
    """Return ``(relative path, size, mtime ns)`` for every file under *path*."""
    if not path.is_dir():
        return []
    return sorted(
        (str(item.relative_to(path)), item.stat().st_size, item.stat().st_mtime_ns)
        for item in path.rglob("*")
        if item.is_file()
    )


def _fail(guard: str, detail: str) -> int:
    print(f"REG208_{guard}_MISSING: {detail}")
    return 1


def _isolated_config_dir(tmp: Path) -> Path:
    cfg_dir = tmp / "user-config"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    os.environ[_CONFIG_DIR_ENV] = str(cfg_dir)
    return cfg_dir


def _check_empty_provider_refused(cfg_dir: Path) -> list[str]:
    """Guard 1: configure_llm refuses an empty provider without writing."""
    from automedia.mcp.tools.setup import configure_llm

    failures: list[str] = []
    result = configure_llm(provider="")
    if result.get("success") is not False:
        failures.append(f"configure_llm(provider='') returned success={result.get('success')!r}")
        return failures
    message = str(result.get("error") or "")
    if "provider" not in message:
        failures.append(f"refusal message does not name the provider: {message!r}")

    written = (cfg_dir / "model_config.yaml").read_text(encoding="utf-8")
    if "provider: ''" in written:
        failures.append("seeded config was left with a blank provider")
    if "provider: amd" not in written:
        failures.append("existing config was modified by the refused write")
    return failures


def _check_backup_before_overwrite(cfg_dir: Path) -> list[str]:
    """Guard 2: a valid configure backs up the previous file before writing."""
    from automedia.mcp.tools.setup import configure_llm

    failures: list[str] = []
    before = (cfg_dir / "model_config.yaml").read_text(encoding="utf-8")

    result = configure_llm(provider="deepseek", model="deepseek-chat")
    if result.get("success") is not True:
        failures.append(f"configure_llm(provider='deepseek') failed: {result!r}")
        return failures

    backups = sorted(cfg_dir.glob("model_config.yaml.bak-*"))
    if not backups:
        failures.append("no model_config.yaml.bak-<timestamp> backup was created")
        return failures

    backup_text = backups[-1].read_text(encoding="utf-8")
    if backup_text != before:
        failures.append("backup does not carry the pre-write content verbatim")

    after = (cfg_dir / "model_config.yaml").read_text(encoding="utf-8")
    if "provider: deepseek" not in after:
        failures.append("the update itself was not written")
    if "fallback-provider" not in after:
        failures.append("the fallback chain was lost on overwrite")
    return failures


def _check_empty_values_refused() -> list[str]:
    """Guards 1b/1c: the library writer refuses blank provider and base_url."""
    from automedia.manifests.model_config_schema import save_model_config

    failures: list[str] = []
    with tempfile.TemporaryDirectory(prefix="reg208-values-") as tmp:
        for key in ("provider", "base_url"):
            try:
                save_model_config(
                    Path(tmp) / "model_config.yaml",
                    {"llm": {"text_generation": {key: "  "}}},
                )
            except ValueError:
                continue
            failures.append(f"empty llm.text_generation.{key} was not rejected")
    return failures


def _check_user_scope_guard(tmp: Path) -> list[str]:
    """Guard 3: the real user config dir refuses writes unless opted in."""
    from automedia.manifests.model_config_schema import save_model_config

    failures: list[str] = []
    fake_home = tmp / "fake-home"
    (fake_home / ".automedia").mkdir(parents=True, exist_ok=True)
    target = fake_home / ".automedia" / "model_config.yaml"
    target.write_text("llm:\n  text_generation:\n    provider: amd\n", encoding="utf-8")

    saved_home = os.environ.get("HOME")
    saved_config_dir = os.environ.pop(_CONFIG_DIR_ENV, None)
    os.environ["HOME"] = str(fake_home)
    try:
        try:
            save_model_config(
                target,
                {"llm": {"text_generation": {"provider": "deepseek"}}},
            )
        except ValueError:
            pass
        else:
            failures.append("a write into the real user config dir was not refused")

        if "provider: amd" not in target.read_text(encoding="utf-8"):
            failures.append("the refused write still modified the file")

        try:
            save_model_config(
                target,
                {"llm": {"text_generation": {"provider": "deepseek"}}},
                allow_user_scope=True,
            )
        except ValueError as exc:
            failures.append(f"explicit opt-in was still refused: {exc}")
        else:
            if "provider: deepseek" not in target.read_text(encoding="utf-8"):
                failures.append("the opted-in write did not land")
    finally:
        os.environ["HOME"] = saved_home if saved_home is not None else ""
        if saved_config_dir is not None:
            os.environ[_CONFIG_DIR_ENV] = saved_config_dir

    if not os.environ.get("HOME"):
        # Path.home() needs $HOME; restore the process default rather than "".
        import pwd

        os.environ["HOME"] = pwd.getpwuid(os.getuid()).pw_dir
    return failures


def _doctor_python() -> list[str]:
    """Return the argv head for a python that can load the ``automedia`` CLI.

    The probe itself only needs the schema/LLM modules, so it may run under a
    slimmer interpreter than ``automedia doctor`` (which imports typer).  Prefer
    the repository's own venv, which is self-contained, and only fall back to
    the current interpreter when there is no venv to run.
    """
    venv_python = _REPO_ROOT / ".venv" / "bin" / "python"
    if venv_python.is_file():
        return [str(venv_python)]
    return [sys.executable]


_REAL_USER_SITE_BASE = site.getuserbase()
"""User-site root captured before any ``HOME`` is patched (doctor is a child)."""


def _check_doctor_flags_empty_provider(tmp: Path) -> list[str]:
    """Guard 4: doctor reports an empty provider as an error, not a warning."""
    failures: list[str] = []
    doctor_home = tmp / "doctor-home"
    cfg_dir = doctor_home / ".automedia"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    (cfg_dir / "model_config.yaml").write_text(
        "llm:\n"
        "  text_generation:\n"
        "    provider: ''\n"
        "    model: DeepSeek-V4-Flash\n"
        "    api_key: ''\n"
        "    base_url: https://example.invalid/v1\n",
        encoding="utf-8",
    )

    env = {
        key: value
        for key, value in os.environ.items()
        if key not in ("AUTOMEDIA_FAKE_LLM", "AUTOMEDIA_LLM_API_KEY")
    }
    env["HOME"] = str(doctor_home)
    env[_CONFIG_DIR_ENV] = str(cfg_dir)
    # The throwaway HOME must not hide the interpreter's user-site install.
    env["PYTHONUSERBASE"] = _REAL_USER_SITE_BASE
    # The child must import the working tree's automedia, not a stale copy.
    inherited_path = env.get("PYTHONPATH")
    env["PYTHONPATH"] = f"{_SRC}{os.pathsep}{inherited_path}" if inherited_path else str(_SRC)

    proc = subprocess.run(  # noqa: S603 — fixed argv, trusted internal command
        [*_doctor_python(), "-m", "automedia", "--json", "doctor"],
        capture_output=True,
        text=True,
        timeout=180,
        env=env,
        cwd=str(doctor_home),
        check=False,
    )

    try:
        payload = json.loads(proc.stdout)
    except ValueError:
        failures.append(f"doctor did not print a JSON payload: {proc.stdout[:200]!r}")
        return failures

    llm_api = next(
        (dep for dep in payload.get("dependencies", []) if dep.get("name") == "llm_api"),
        None,
    )
    if llm_api is None:
        failures.append("doctor payload carries no llm_api dependency entry")
    elif llm_api.get("installed") is not False:
        failures.append(
            f"an empty provider reported llm_api installed={llm_api.get('installed')!r} "
            f"({llm_api.get('version')!r}) — the corruption is masked again"
        )
    elif "provider is empty" not in str(llm_api.get("version") or ""):
        failures.append(f"llm_api error does not name the empty provider: {llm_api!r}")
    return failures


def main() -> int:
    real_config_dir = Path.home() / ".automedia"
    before = _snapshot_dir(real_config_dir)

    with tempfile.TemporaryDirectory(prefix="reg208-") as tmp:
        root = Path(tmp)
        cfg_dir = _isolated_config_dir(root)
        (cfg_dir / "model_config.yaml").write_text(_SEEDED_CONFIG, encoding="utf-8")

        failures: list[str] = []
        # A guard that cannot even run is a guard that does not hold: a crash
        # must be reported as a violation, not abort the whole probe.
        checks: tuple[tuple[str, Callable[[], list[str]]], ...] = (
            ("empty provider", lambda: _check_empty_provider_refused(cfg_dir)),
            ("backup", lambda: _check_backup_before_overwrite(cfg_dir)),
            ("empty values", _check_empty_values_refused),
            ("user scope", lambda: _check_user_scope_guard(root)),
            ("doctor", lambda: _check_doctor_flags_empty_provider(root)),
        )
        for guard, check in checks:
            try:
                failures += check()
            except Exception as exc:  # the probe reports every violation, never aborts
                failures.append(f"{guard} check raised {type(exc).__name__}: {exc}")

    after = _snapshot_dir(real_config_dir)
    if after != before:
        print("REG208_REAL_CONFIG_DIR_TOUCHED: the real user config directory changed")
        return 1

    if failures:
        for failure in failures:
            print(f"REG208_GUARD_VIOLATION: {failure}")
        return 1

    print("REG208_GUARDS_ENFORCED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
